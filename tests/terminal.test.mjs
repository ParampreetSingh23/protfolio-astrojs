import assert from 'node:assert/strict';
import { runCommand, resolvePath, openPath } from '../src/scripts/terminal.ts';

assert.deepEqual(runCommand('./github.sh').action, { type: 'browser', url: 'https://github.com/ParampreetSingh23' });
assert.deepEqual(runCommand('bash linkedin.sh').action?.type, 'browser');
assert.match(runCommand('./projects.sh').text, /drip/);
assert.match(runCommand('./projects.sh DRIP').text, /AWS ECS/);
assert.equal(runCommand('./projects.sh campusbarter').action?.url, 'https://campusbarter.onrender.com');
assert.match(runCommand('./projects.sh nope').text, /no project named/);
assert.match(runCommand('./experience.sh').text, /Rabbitt AI/);
assert.match(runCommand('./skills.sh').text, /BullMQ/);
assert.equal(runCommand('./contact.sh').links?.[0].href, 'mailto:parampreetsinghlall@gmail.com');
assert.match(runCommand('./evil.sh').text, /No such file/);
assert.match(runCommand('ls').text, /projects\//);
assert.match(runCommand('ls projects').text, /tisiops\.md/);
assert.equal(runCommand('cd projects').cwd, '~/Desktop/projects');
assert.match(runCommand('cat drip.md', '~/Desktop/projects').text, /# DRIP/);
assert.match(runCommand('../github.sh', '~/Desktop/projects').text, /Launching browser/);
assert.match(runCommand('cat about.txt').text, /CGPA 9\.44/);
assert.match(runCommand('cat projects').text, /Is a directory/);
assert.deepEqual(runCommand('open resume.pdf').action, { type: 'browser', url: '/resume.pdf' });
assert.deepEqual(openPath('~/Desktop/projects').action, { type: 'files', path: '~/Desktop/projects' });
assert.deepEqual(openPath('~/Desktop/about.txt').action, { type: 'editor', path: '~/Desktop/about.txt' });
assert.equal(resolvePath('~/Desktop', '../../../..'), '~');
assert.equal(runCommand('clear').clear, true);
assert.equal(runCommand('').text, '');
assert.match(runCommand('<script>alert(1)</script>').text, /command not found/);
assert.ok(runCommand('x'.repeat(1000)).text.length < 120);
console.log('Terminal commands: passed.');
